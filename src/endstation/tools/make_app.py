#!/usr/bin/env python
"""Build a macOS ``.app`` that launches a project's GUI.

    endstation-app --name "GratingLab" --script gratinglab-gui \
                   --bundle-id org.gratinglab.gui --icon resources/GratingLab.icns

Not a frozen bundle -- no PyInstaller, no embedded interpreter. Three files: a
plist, a shell stub that execs the console script, and the icon. Enough for a
Dock icon and a double-clickable launcher, and it rebuilds in a second.

Two stub generations existed, and both are kept.

``thin`` is a two-line ``exec``. Smallest thing that works.

``logging`` (the default) sends output to ``~/Library/Logs/<stem>.log`` and
raises a native alert naming that log if the GUI exits non-zero. That exists
because **a .app that fails silently is useless**: a missing virtualenv
otherwise just bounces the icon once and gives no clue why. Two projects wrote
that stub independently after hitting exactly this; it is the better default,
and the thin one stays available for a launcher that is only ever run from a
terminal-adjacent context.

``LSMinimumSystemVersion`` is not a preference. PySide6-Essentials ships as
``macosx_13_0_universal2``, so a GUI extra cannot install below macOS 13.
Claiming 11.0 would let Finder launch a bundle whose window can never open.
Projects with no Qt dependency can lower it explicitly.
"""

from __future__ import annotations

import argparse
import plistlib
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

__all__ = ["App", "LOGGING_STUB", "THIN_STUB", "build_app", "check_app"]

#: PySide6-Essentials wheels are tagged macosx_13_0. See the module docstring.
DEFAULT_MIN_MACOS = "13.0"

THIN_STUB = """#!/bin/sh
# Generated by endstation-app -- edit the generator, not this.
exec "{launcher}" "$@"
"""

LOGGING_STUB = """#!/bin/bash
# Generated by endstation-app -- edit the generator, not this.
LAUNCHER="{launcher}"
LOG="$HOME/Library/Logs/{stem}.log"
mkdir -p "$(dirname "$LOG")"

fail() {{
    /usr/bin/osascript -e "display alert \\"{name} could not start\\" \\
        message \\"$1

Log: $LOG\\" as critical" >/dev/null 2>&1
    exit 1
}}

[ -x "$LAUNCHER" ] || fail "The launcher is missing:
$LAUNCHER

The virtualenv this bundle points at has moved or been rebuilt.
Reinstall the package and re-run endstation-app."

echo "--- $(date) ---" >> "$LOG"
"$LAUNCHER" "$@" >> "$LOG" 2>&1 || fail "{name} exited with an error."
"""


@dataclass(frozen=True)
class App:
    """One window's bundle identity.

    ``stem`` carries no spaces: it names the executable, the icon file and the
    iconset directory inside the bundle, where a space is a nuisance rather than
    an error. It defaults to ``name`` with spaces removed.
    """

    name: str
    launcher: Path
    bundle_id: str
    stem: str = ""
    icon: Path | None = None
    version: str = "0.0.0"
    min_macos: str = DEFAULT_MIN_MACOS

    def __post_init__(self) -> None:
        if not self.stem:
            object.__setattr__(self, "stem", self.name.replace(" ", ""))


def build_app(
    app: App,
    destination: Path,
    *,
    stub: str = "logging",
) -> Path:
    """Write ``<destination>/<stem>.app``. Returns its path."""
    if sys.platform != "darwin":
        raise SystemExit(".app bundles are macOS-only")
    if not Path(app.launcher).exists():
        raise SystemExit(
            f"{app.launcher} not found -- install the package first, e.g.\n"
            "    pip install -e '.[gui]'"
        )
    if app.icon is not None and not Path(app.icon).exists():
        raise SystemExit(
            f"{app.icon} not found -- run endstation-icon to generate it"
        )

    bundle = Path(destination) / f"{app.stem}.app"
    contents = bundle / "Contents"
    if bundle.exists():
        shutil.rmtree(bundle)
    (contents / "MacOS").mkdir(parents=True)
    (contents / "Resources").mkdir(parents=True)

    info = {
        "CFBundleName": app.name,
        "CFBundleDisplayName": app.name,
        "CFBundleExecutable": app.stem,
        "CFBundleIdentifier": app.bundle_id,
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": app.version,
        "CFBundleVersion": app.version,
        "LSMinimumSystemVersion": app.min_macos,
        # Without this the window renders blurry on a Retina display.
        "NSHighResolutionCapable": True,
    }
    if app.icon is not None:
        info["CFBundleIconFile"] = app.stem
    (contents / "Info.plist").write_bytes(plistlib.dumps(info))

    template = {"thin": THIN_STUB, "logging": LOGGING_STUB}[stub]
    executable = contents / "MacOS" / app.stem
    executable.write_text(
        template.format(launcher=app.launcher, stem=app.stem, name=app.name),
        encoding="utf-8",
    )
    executable.chmod(0o755)

    if app.icon is not None:
        shutil.copy2(app.icon, contents / "Resources" / f"{app.stem}.icns")

    # Finder caches icons aggressively; touching the bundle nudges it.
    subprocess.run(["touch", str(bundle)], check=False)
    return bundle


def check_app(bundle: Path) -> list[str]:
    """Report what is wrong with an existing bundle. Empty list means it is fine.

    Worth having because the usual breakage is invisible from the outside: the
    repository moved, so the stub points at a virtualenv that is no longer
    there, and the only symptom is an icon that bounces once.
    """
    bundle = Path(bundle)
    problems: list[str] = []

    if not bundle.is_dir():
        return [f"{bundle} does not exist"]

    plist = bundle / "Contents" / "Info.plist"
    if not plist.is_file():
        problems.append("Contents/Info.plist is missing")
        return problems

    info = plistlib.loads(plist.read_bytes())
    stem = info.get("CFBundleExecutable", "")
    executable = bundle / "Contents" / "MacOS" / stem
    if not executable.is_file():
        problems.append(f"Contents/MacOS/{stem} is missing")
    else:
        import os

        if not os.access(executable, os.X_OK):
            problems.append(f"Contents/MacOS/{stem} is not executable")
        # The stub names its launcher; check that it still exists.
        # Lenient: the stub is ours, but a bundle can be edited by hand, and a
        # check that crashes on a stray byte reports nothing at all.
        text = executable.read_text(encoding="utf-8", errors="replace")
        for line in text.splitlines():
            if line.startswith(('exec "', 'LAUNCHER="')):
                target = line.split('"')[1]
                if not Path(target).exists():
                    problems.append(f"launcher no longer exists: {target}")
                break

    if info.get("CFBundleIconFile"):
        icon = bundle / "Contents" / "Resources" / f"{info['CFBundleIconFile']}.icns"
        if not icon.is_file():
            problems.append(f"icon is missing: {icon.name}")

    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--name", help='display name, e.g. "AFM Blaze Meas"')
    parser.add_argument("--script", help="console script to exec, e.g. mypkg-gui")
    parser.add_argument("--bundle-id", help="e.g. org.example.myapp")
    parser.add_argument("--stem", default="",
                        help="executable/icon name; defaults to --name without spaces")
    parser.add_argument("--icon", type=Path, default=None, help="path to an .icns")
    parser.add_argument("--version", default="0.0.0")
    parser.add_argument("--min-macos", default=DEFAULT_MIN_MACOS)
    parser.add_argument("--venv", type=Path, default=Path(".venv"),
                        help="virtualenv holding the console script (default: .venv)")
    parser.add_argument("--dest", type=Path, default=Path("build"),
                        help="where to write the .app (default: ./build)")
    parser.add_argument("--stub", choices=("logging", "thin"), default="logging",
                        help="logging writes ~/Library/Logs and alerts on failure")
    parser.add_argument("--check", type=Path, default=None,
                        help="verify an existing bundle instead of building one")
    args = parser.parse_args(argv)

    if args.check is not None:
        problems = check_app(args.check)
        if problems:
            print(f"{args.check} has problems:")
            for problem in problems:
                print(f"  - {problem}")
            return 1
        print(f"{args.check} looks correct")
        return 0

    missing = [n for n in ("name", "script", "bundle_id")
               if not getattr(args, n)]
    if missing:
        parser.error("--" + ", --".join(m.replace("_", "-") for m in missing)
                     + " required unless --check is given")

    app = App(
        name=args.name,
        launcher=Path(args.venv).resolve() / "bin" / args.script,
        bundle_id=args.bundle_id,
        stem=args.stem,
        icon=args.icon,
        version=args.version,
        min_macos=args.min_macos,
    )
    args.dest.mkdir(parents=True, exist_ok=True)
    bundle = build_app(app, args.dest, stub=args.stub)

    print(f"wrote {bundle}")
    print(f"  launches: {app.launcher}")
    print(f"\nopen '{bundle}'   # or drag it to /Applications")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
